/* ─────────────────────────────────────────────────────────────────────────
   The clinician summary — everything the assessment worked out, written for
   Chandra rather than for the patient, in the order of the CPA Orthopaedic
   Division subjective booklet:

     body chart (P1/P2/P3) → history → pain mechanisms → SIN and irritability
     → 24-hour pattern, aggravating and easing → safety and cautions
     → flags (yellow / blue / black / pink) → hypotheses with the subjective
     findings that support each → examination considerations

   It is built from the SAME rule output the patient screen uses, plus the
   answers themselves, so it can never say something the tool did not work
   out. Nothing here is generated by the AI except, where it ran, a line
   recording what the reasoning pass changed.

   The patient can read it — it is their own information — but it is written
   in clinical language and kept behind a disclosure on the result screen.
   ───────────────────────────────────────────────────────────────────────── */
import { REGIONS, allQuestions } from './symptomGuide.js'
import { REFERRAL_MAP, SCREENING_SEQUENCE, mappedTypes, organsForType } from './referralMap.js'

/* The CPA Orthopaedic Division subjective booklet asks for the two most
   likely hypotheses. The result screen shows the same two, so the patient's
   page and Chandra's summary can never disagree. */
export const MAX_HYPOTHESES = 2
/* Drawn areas the referral-sources section covers, so it stays readable. */
const MAX_REFERRAL_AREAS = 4

const line = (label, value) => (value ? `${label}: ${value}` : null)
const listOf = (items, bullet = '  - ') => (items || []).filter(Boolean).map((t) => bullet + t)

/** The answers that actually scored FOR one condition — its supporting
    subjective findings, in the patient's own answers. */
export function supportingFindings(regionKey, conditionId, answers = {}) {
  const region = REGIONS[regionKey]
  if (!region) return []
  const out = []
  for (const q of allQuestions(region)) {
    const a = answers[q.id]
    if (a === undefined) continue
    const picked = Array.isArray(a) ? a : [a]
    for (const oid of picked) {
      const o = (q.options || []).find((x) => x.id === oid)
      const w = o && o.weights ? o.weights[conditionId] : 0
      if (w > 0) out.push({ question: q.text, answer: o.label, weight: w })
    }
  }
  return out.sort((a, b) => b.weight - a.weight)
}

/** Findings that argue AGAINST a condition (negative weights) — useful when
    the reasoning pass or the clinician wants to know why something is lower. */
export function againstFindings(regionKey, conditionId, answers = {}) {
  const region = REGIONS[regionKey]
  if (!region) return []
  const out = []
  for (const q of allQuestions(region)) {
    const a = answers[q.id]
    if (a === undefined) continue
    for (const oid of Array.isArray(a) ? a : [a]) {
      const o = (q.options || []).find((x) => x.id === oid)
      if (o && o.weights && o.weights[conditionId] < 0) out.push(`${o.label}`)
    }
  }
  return out
}

const AREA_ORDER = ['neck', 'ctj', 'upperback', 'chest', 'tlj', 'flank', 'lowerback', 'abdomen', 'shoulder', 'elbow', 'wrist', 'hip', 'knee', 'ankle', 'head']

/** P1 / P2 / P3 — the drawn areas, spine first, with surface and side.
    Areas a referral line merely travels through are where the pain is FELT,
    not separate problems, so they are left out here and described with the
    line itself. */
export function painAreas(zones = [], referral = []) {
  const felt = new Set(referral.flatMap((r) => r.felt || []))
  const seen = new Map()
  for (const z of zones) {
    if (felt.has(z.id)) continue
    if (!seen.has(z.id)) seen.set(z.id, { label: z.label, type: z.type, face: z.face || null })
  }
  return [...seen.values()]
    .sort((a, b) => AREA_ORDER.indexOf(a.type) - AREA_ORDER.indexOf(b.type))
    .slice(0, 3)
    .map((z, i) => `P${i + 1}: ${z.label}${z.face ? ` (${z.face} surface)` : ''}`)
}

const MECHANISM_LABEL = {
  nociceptive: 'Nociceptive',
  neuropathic: 'Peripheral neuropathic',
  nociplastic: 'Central / nociplastic',
}

/** The whole summary as plain text, ready to copy or send. */
export function buildClinicianSummary(ctx = {}) {
  const {
    zones = [], referral = [], keys = [], answers = {}, qaPairs = [], notes = '',
    ranked = [], behaviour = {}, psych = {}, painType = null,
    cautions = [], declinedFlags = [], review = null, date = new Date(),
  } = ctx

  const L = []
  // '' is a deliberate blank line between sections; only null/undefined are skipped.
  const push = (...xs) => xs.forEach((x) => { if (x !== null && x !== undefined && x !== false) L.push(x) })

  push('PHYSIO CHANDRA — ONLINE SUBJECTIVE SCREEN',
    `Completed: ${date.toISOString().slice(0, 10)}`,
    'Self-reported by the patient online. Not an examination; to be confirmed at assessment.',
    '')

  // ── Body chart ──
  push('BODY CHART')
  push(...painAreas(zones, referral).map((s) => '  ' + s))
  for (const r of referral) {
    const where = `${r.side ? r.side + ' ' : ''}${r.kind}`.trim()
    push(`  Referred into the ${where}, as far as the ${r.reach} — one continuous line from the ${r.kind === 'arm' ? 'neck' : 'low back'}`)
  }
  if (keys.length) push(`  Questions asked from: ${keys.map((k) => (REGIONS[k] ? REGIONS[k].name : k)).join(', ')}`)
  push('')

  // ── Referral sources (Referred Pain Clinical Reference, ./referralMap.js) ──
  // Every drawn area, including those a referral line only travels through:
  // those are exactly where joint, root and muscle referral is felt.
  const mapped = mappedTypes(zones).slice(0, MAX_REFERRAL_AREAS)
  if (mapped.length) {
    push('REFERRAL SOURCES TO CONSIDER (from the body chart; possibilities, not findings)')
    for (const t of mapped) {
      const m = REFERRAL_MAP[t]
      const label = (zones.find((z) => z.type === t) || {}).label || t
      push(`  ${label}:`)
      if (m.joints.length) push(`      Joints / discs: ${m.joints.join('; ')}`)
      if (m.roots.length) push(`      Nerve roots: ${m.roots.join('; ')}`)
      if (m.muscles.length) push(`      Muscles: ${m.muscles.join('; ')}`)
      const organs = organsForType(t, zones)
      if (organs.length) push(`      Organs to clear if it is not mechanical: ${organs.join('; ')}`)
    }
    if (referral.length) {
      push('  Distance alone does not prove a nerve root: facets, discs, the SIJ, the hip and gluteus minimus',
        '  can refer past the knee or elbow, and radicular pain rarely follows one dermatome (Bogduk 2009;',
        '  Murphy 2009; Lesher 2008). Distal pins and needles are the more localising sign.')
    }
    push('  Screening sequence:')
    push(...SCREENING_SEQUENCE.map((s, i) => `      ${i + 1}. ${s}`))
    push('')
  }

  // ── History ──
  const history = qaPairs.filter((p) => /your age|how long has it been|did it (start|begin)/i.test(p.question))
  if (history.length) {
    push('HISTORY')
    push(...history.map((p) => `  ${p.question} ${p.answer}`))
    push('')
  }

  // ── Pain mechanisms (the booklet's question 1) ──
  push('PAIN MECHANISMS — evidence from the subjective screen')
  if (painType) {
    const order = [painType.primary, painType.secondary].filter(Boolean)
    for (const t of order) {
      const sub = t === 'nociceptive' && painType.subtype ? ` (${painType.subtype})` : ''
      push(`  ${MECHANISM_LABEL[t]}${sub}${t === painType.primary ? '  ← dominant' : ''}`)
      push(...listOf(painType.reasons[t], '      · '))
    }
    for (const t of Object.keys(MECHANISM_LABEL)) {
      if (!order.includes(t)) push(`  ${MECHANISM_LABEL[t]}: no supporting evidence in this screen`)
    }
  } else {
    push('  Not enough information in this screen to weigh the mechanisms.')
  }
  push('')

  // ── SIN / irritability (questions 3a–3c) ──
  push('SEVERITY, IRRITABILITY, NATURE')
  push(line('  Irritability', behaviour.irritability ? behaviour.irritability.toUpperCase() : 'not established'))
  push(...listOf(behaviour.evidence, '      · '))
  if (behaviour.examCaution) push('  Implication for the physical examination:', '      ' + behaviour.examCaution)
  push('')

  // ── Behaviour ──
  const behaviourQs = qaPairs.filter((p) => /worst|settle|eases|brings the pain on|how does the pain feel/i.test(p.question))
  if (behaviourQs.length) {
    push('BEHAVIOUR (24-hour pattern, aggravating and easing)')
    push(...behaviourQs.map((p) => `  ${p.question} ${p.answer}`))
    push('')
  }

  // ── Safety and cautions (question 4) ──
  push('SAFETY SCREEN')
  push('  Red flags: none reported (the patient reached the result screen, which red flags prevent).')
  if (declinedFlags.length) push(`  Screened and denied: ${declinedFlags.join('; ')}`)
  if (cautions.length) {
    push('  CAUTIONS reported — adjust the first physical examination:')
    push(...listOf(cautions.map((c) => `${c.text} — ${c.why.text}`), '      · '))
  } else {
    push('  Cautions: none reported.')
  }
  push('')

  // ── Flags (question 5) ──
  const f = psych.flags || { yellow: [], blue: [], black: [], pink: [] }
  push('FLAGS')
  push(`  Yellow (${f.yellow.length}): ${f.yellow.length ? f.yellow.join(' | ') : 'none endorsed'}`)
  push(`  Blue: ${f.blue.length ? f.blue.join(' | ') : 'none endorsed'}`)
  push(`  Black: ${f.black.length ? f.black.join(' | ') : 'none endorsed'}`)
  push(`  Pink (protective): ${f.pink.length ? f.pink.join(' | ') : 'none endorsed'}`)
  if (psych.level) push(`  Psychosocial risk from this screen: ${psych.level}`)
  push('')

  // ── Hypotheses with supporting findings (question 6) ──
  push('HYPOTHESES FROM THE SUBJECTIVE SCREEN')
  if (!ranked.length) {
    push('  No pattern in the clinic library matched these answers well enough to name.')
  } else {
    // Two hypotheses, as the subjective booklet asks for.
    ranked.slice(0, MAX_HYPOTHESES).forEach((x, i) => {
      const c = x.c
      push(`  H${i + 1}: ${c.name}${c.clin ? ` — ${c.clin}` : ''}  [${REGIONS[x.rk] ? REGIONS[x.rk].name : x.rk}]`)
      const support = supportingFindings(x.rk, c.id, answers).slice(0, 4)
      push(...listOf(support.map((s) => `${s.answer}  (${s.question})`), '      · '))
      const against = againstFindings(x.rk, c.id, answers)
      if (against.length) push(`      Against: ${against.join('; ')}`)
    })
  }
  if (review) {
    const bits = []
    if (review.order && review.order.length) bits.push(`re-ranked to ${review.order.join(' > ')}`)
    if (review.dropped && review.dropped.length) bits.push(`dropped ${review.dropped.map((d) => `${d.id} (${d.why})`).join(', ')}`)
    if (review.noMatch) bits.push('judged that none fit')
    if (review.concern) bits.push(`raised for medical review: ${review.concern.why}`)
    if (bits.length) push('', `  AI reasoning pass: ${bits.join('; ')}.`, review.note ? `  Its note: ${review.note}` : null)
  }
  push('')

  // ── Examination considerations (question 7, as far as a screen can go) ──
  push('EXAMINATION CONSIDERATIONS')
  if (behaviour.examCaution) push('  ' + behaviour.examCaution)
  if (painType && (painType.primary === 'neuropathic' || painType.secondary === 'neuropathic')) {
    push('  Nerve-type symptoms reported — include neurological conduction (myotomes, dermatomes, reflexes) and neurodynamic testing, sequenced by irritability.')
  }
  if (referral.length) {
    push(`  Referral pattern drawn — examine the ${referral[0].kind === 'arm' ? 'cervical spine' : 'lumbar spine'} as a source, and clear the local ${referral[0].kind} structures as alternatives.`)
  }
  if (painType && painType.subtype === 'inflammatory') {
    push('  Inflammatory pattern reported (prolonged morning stiffness, worse after rest) — consider screening questions for inflammatory arthropathy and a physician opinion if it persists.')
  }
  if (psych.level === 'high' || (f.yellow || []).length >= 3) {
    push('  Several yellow flags endorsed — consider a psychosocially informed approach and outcome measures at the first visit.')
  }
  push('')

  if (notes && notes.trim()) push('IN THE PATIENT\'S OWN WORDS', '  ' + notes.trim(), '')

  push('Generated by the Physio Chandra online screen from the patient\'s answers.',
    'Possibilities only — not a diagnosis, and no substitute for your assessment.')

  return L.join('\n')
}
