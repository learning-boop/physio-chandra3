/* Turns the Markdown files in content/conditions/ into a data module that the
   app merges into REGIONS at load time.

   Adding a condition is really TWO edits: the condition record, and weights on
   the question options that point at it. Authors only write plain answer text
   ("First steps in the morning"); this script resolves that to the option id
   and attaches the weight, so the two halves can never drift apart.

   Run: npm run import:conditions          */
import fs from 'fs'
import path from 'path'
import { REGIONS, allQuestions } from '../src/data/symptomGuide.js'

const DIR = 'content/conditions'
const OUT = 'src/data/symptomGuideAuthored.js'

const files = fs.existsSync(DIR)
  ? fs.readdirSync(DIR).filter((f) => f.endsWith('.md') && !f.startsWith('_'))
  : []

let errors = 0
const fail = (f, m) => { console.error(`  ERROR  ${f}: ${m}`); errors++ }

function parse(file) {
  const raw = fs.readFileSync(path.join(DIR, file), 'utf8')
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/)
  if (!m) { fail(file, 'missing the --- front matter block'); return null }
  const [, head, bodyText] = m

  const meta = {}
  const pointers = {}
  let inPointers = false
  for (const line of head.split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    if (/^pointers:/.test(t)) { inPointers = true; continue }
    const kv = t.match(/^"?([^":]+)"?\s*:\s*(.*)$/)
    if (!kv) continue
    if (inPointers && /^\s/.test(line)) {
      const p = t.match(/^"(.+)"\s*:\s*(-?\d+)\s*$/)
      if (!p) { fail(file, `pointer line must be  "answer text": number  — got: ${t}`); continue }
      pointers[p[1]] = Number(p[2])
    } else { inPointers = false; meta[kv[1].trim()] = kv[2].trim() }
  }

  const sections = {}
  for (const part of bodyText.split(/^##\s+/m).slice(1)) {
    const nl = part.indexOf('\n')
    const key = part.slice(0, nl).trim()
    const val = part.slice(nl + 1).trim()
    sections[key] = /^-\s/m.test(val)
      ? val.split(/\r?\n/).filter((l) => l.trim().startsWith('- ')).map((l) => l.trim().slice(2).trim())
      : val.replace(/\s*\n\s*/g, ' ').trim()
  }
  return { file, meta, pointers, sections }
}

const authored = []
for (const file of files) {
  const doc = parse(file)
  if (!doc) continue
  const { meta, pointers, sections } = doc
  const region = REGIONS[meta.region]
  if (!region) { fail(file, `unknown region "${meta.region}"`); continue }
  if (!meta.id || !meta.name) { fail(file, 'id and name are required'); continue }
  if (region.conditions.some((c) => c.id === meta.id)) { fail(file, `id "${meta.id}" already exists in ${meta.region}`); continue }
  for (const k of ['blurb', 'noticed', 'homeCare', 'seePhysioIf']) {
    if (!sections[k] || !sections[k].length) fail(file, `## ${k} section is empty`)
  }

  // Resolve each pointer's answer text to a real option in this region.
  const resolved = []
  for (const [text, weight] of Object.entries(pointers)) {
    let hit = null
    for (const q of allQuestions(region)) {
      const o = (q.options || []).find((x) => x.label.toLowerCase().includes(text.toLowerCase()))
      if (o) { hit = { qid: q.id, oid: o.id, label: o.label }; break }
    }
    if (!hit) fail(file, `no answer option in "${meta.region}" matches "${text}"`)
    else resolved.push({ ...hit, weight })
  }
  if (!resolved.length) fail(file, 'no pointers — this condition could never be shown')
  if (resolved.length !== Object.keys(pointers).length || !resolved.length) continue

  authored.push({ region: meta.region, cond: {
    id: meta.id, name: meta.name, clin: meta.clin || '',
    blurb: sections.blurb, noticed: sections.noticed,
    homeCare: sections.homeCare, seePhysioIf: sections.seePhysioIf,
  }, resolved })
  console.log(`  ok     ${file} -> ${meta.region}/${meta.id}  (${resolved.length} pointers)`)
}

if (errors) { console.error(`\n${errors} error(s) — nothing written.`); process.exit(1) }

const body = `/* GENERATED by scripts/import-conditions.mjs — do not edit by hand.
   Source: ${DIR}/*.md   (${authored.length} authored condition${authored.length === 1 ? '' : 's'})
   Data only, no side effects: symptomGuide.js merges this into REGIONS. */
export const AUTHORED = ${JSON.stringify(authored, null, 2)}
`
fs.writeFileSync(OUT, body)
console.log(`\nWrote ${OUT} — ${authored.length} condition(s) from ${files.length} file(s).`)
